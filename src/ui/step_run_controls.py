# -*- coding: utf-8 -*-
"""Build inspector run controls; temporary arguments remain session-only state."""

def create_step_run_controls(panel, *, ui):
    # 高频运行操作：不依赖编辑模式。
    run_row = ui.QWidget()
    run_row.setSizePolicy(ui.QSizePolicy.Expanding, ui.QSizePolicy.Fixed)
    run_row_layout = ui.QVBoxLayout(run_row)
    run_row_layout.setContentsMargins(0, 0, 0, 0)
    run_row_layout.setSpacing(6)
    panel.btn_run_only_step = ui.QPushButton("只运行此步骤")
    panel.btn_run_only_step.setObjectName("stepRunButton")
    panel.btn_run_only_step.setFixedHeight(30)
    panel.btn_run_only_step.setMinimumWidth(0)
    panel.btn_run_only_step.setSizePolicy(ui.QSizePolicy.Expanding, ui.QSizePolicy.Fixed)
    panel.btn_run_only_step.setToolTip("只运行当前选中的步骤")
    panel.btn_run_only_step.setAccessibleName("只运行此步骤")
    panel.btn_run_only_step.clicked.connect(lambda: panel._request_step_run("only_step"))
    only_step_row = ui.QWidget()
    only_step_layout = ui.QHBoxLayout(only_step_row)
    only_step_layout.setContentsMargins(0, 0, 0, 0)
    only_step_layout.setSpacing(8)
    only_step_layout.addWidget(panel.btn_run_only_step, stretch=1)
    panel.check_modify_run_args = ui.QCheckBox("本次修改参数")
    panel.check_modify_run_args.setChecked(False)
    panel.check_modify_run_args.setToolTip("勾选后，运行前设置本次临时参数；不改变步骤默认配置")
    panel.check_modify_run_args.setAccessibleName("本次修改参数")
    only_step_layout.addWidget(panel.check_modify_run_args)
    run_row_layout.addWidget(only_step_row)
    panel.btn_run_from_step = ui.QPushButton("从此步骤开始")
    panel.btn_run_from_step.setObjectName("stepRunButton")
    panel.btn_run_from_step.setFixedHeight(30)
    panel.btn_run_from_step.setMinimumWidth(0)
    panel.btn_run_from_step.setSizePolicy(ui.QSizePolicy.Expanding, ui.QSizePolicy.Fixed)
    panel.btn_run_from_step.setToolTip("从当前步骤开始运行后续步骤")
    panel.btn_run_from_step.setAccessibleName("从此步骤开始")
    panel.btn_run_from_step.clicked.connect(lambda: panel._request_step_run("from_step"))
    run_row_layout.addWidget(panel.btn_run_from_step)
    return run_row
